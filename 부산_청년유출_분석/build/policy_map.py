"""부산 청년정책 109개 → 그룹계열 13종 × 성격(양성/매칭/창업/생활지원) 분류.

계열: 사업명이 특정 전공 인력을 명시하면 그 계열, 아니면 '전계열'(대상 무관).
성격: 공급(양성) / 수요·매칭 / 창업 / 생활지원 — 우리 논지의 핵심 축이다.
판단이 들어가므로 CSV로 빼서 팀이 수정할 수 있게 한다.
"""
import re, pandas as pd

계열 = [
 ("IT·컴퓨터",   r"인공지능|소프트웨어|SW중심|ICT|디지털혁신아카데미|클라우드"),
 ("기계·전기전자", r"반도체|공학인재|기술사관|조선해양플랜트|신발산업"),
 ("물류·운송",   r"항만물류|해운항만|항공인력"),
 ("디자인·예술", r"패션디자인|콘텐츠 아카데미|웹툰|신진예술인|로컬크리에이터|신진작가|작품제작|콘텐츠유니버시아드|인디스테이션|이스포츠"),
 ("경영·사무",  r"국제금융기구|국제마케팅|해양금융"),
 ("보건·의료",  r"치의학"),
 ("건설·토목",  r"도시재생사"),
 ("농림·수산",  r"어촌 정착|농업인 영농"),
]
성격 = [
 ("수요·매칭",  r"일자리\(플러스\)센터|취업네트워크|청끌기업|고용 우수기업|지역주도형 청년일자리|취업연수생|인턴십|합동채용설명회|해외취업|현장실습|코업|정장 대여|사회진입 활동비|청년도전|두드림센터|어촌 정착|영농정착"),
 ("창업",      r"창업|스타트업|크리에이터"),
 ("양성",      r"양성|아카데미|육성|인력|교육지원|계약학과|캠퍼스|훈련|장학금|학자금|대학지원|혁신파크|LINC|RIS|글로컬|NEXT10|인재"),
]
def pick(name, rules, default):
    for k, p in rules:
        if re.search(p, name): return k
    return default

d = pd.read_csv("data/부산데이터/청년지원정책.csv"); d.columns = [c.strip() for c in d.columns]
d["계열"] = d.세부사업명.map(lambda s: pick(s, 계열, "전계열"))
d["성격"] = [pick(s, 성격, "생활지원" if f in ("주거","복지문화","참여권리","문화") else "생활지원")
             for s, f in zip(d.세부사업명, d.분야)]
out = d[["세부사업명","분야","계열","성격","취창업 여부","예산(천원)"]].rename(columns={"예산(천원)":"예산_백만원"})
out.to_csv("out/정책_계열분류.csv", index=False, encoding="utf-8-sig")

print("■ 계열 × 성격 교차")
print(pd.crosstab(out.계열, out.성격, margins=True).to_string())
print("\n■ 계열이 명시된 사업 (전계열 제외)")
sp = out[out.계열 != "전계열"]
t = sp.groupby(["계열","성격"]).size().unstack(fill_value=0)
for c in ["양성","수요·매칭","창업","생활지원"]:
    if c not in t: t[c] = 0
t = t[["양성","수요·매칭","창업","생활지원"]]
t["계"] = t.sum(axis=1)
print(t.sort_values("계", ascending=False).to_string())
print(f"\n계열 명시 {len(sp)}개 / 전계열 {len(out)-len(sp)}개")
