def build():
    m = Master()
    rep = {}
    for c, nm in sorted(m.name.items()):
        rep.setdefault(c[:2], []).append(nm)
    with MAP.open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["KECO중분류", "세세분류수", "대표명칭", "직종분류코드", "직종분류명", "근거"])
        for k, code, why in RULE:
            names = rep.get(k, [])
            w.writerow([k, len(names), " / ".join(names[:3])[:70],
                        code, NAMES[code], why])
    print(f"{MAP.relative_to(BASE)}  {len(RULE)}행")
    # 누락 검사 — 마스터에 있는 2자리가 규칙에 다 있는지
    miss = sorted(set(rep) - {k for k, _, _ in RULE})
    print("규칙 누락:", miss or "없음")


def load():
    """{KECO 2자리: (13분류코드, 13분류명)}"""
    if not MAP.exists():
        build()
    d = {}
    for r in csv.DictReader(MAP.open(encoding="utf-8-sig")):
        d[r["KECO중분류"]] = (r["직종분류코드"], r["직종분류명"])
    return d


def of(code):
    """6자리(또는 2자리 이상 접두) -> (13분류코드, 13분류명). 못 정하면 ('','')"""
    t = load()
    if not code:
        return "", ""
    if len(code) >= 2 and code[:2] in t:
        return t[code[:2]]
    # 1자리만 있으면 그 대분류에 속한 2자리들이 한 곳으로 모일 때만 확정
    cands = {v for k, v in t.items() if k[:1] == code[:1]}
    return cands.pop() if len(cands) == 1 else ("", "")


