def build(min_n=2, min_purity=0.5, min_n6=3, min_purity6=0.6):
    """min_n6/min_purity6 는 6자리 채택 기준. 13분류보다 엄격하다.

    처음엔 6자리도 2건·50% 로 받았더니 `조경 -> 140400`(정답 4건 중 2건)이
    토목·기계 건설사업관리 공고에 붙었다. 표본이 작을 때 50% 는 동전 던지기다.
    """
    m = Master()
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from keco_run import leakfree_tokens, load
    rows = load()
    gold = [r for r in rows
            if m.exact.get(norm(r["직종"] or "")) or m.exact.get(core_of(r["직종"] or ""))]
    per = collections.defaultdict(collections.Counter)
    for r in gold:
        c = m.exact.get(norm(r["직종"])) or m.exact.get(core_of(r["직종"]))
        for t in leakfree_tokens(r):
            if t in m.exact or t in m.alias:
                continue
            per[t][c] += 1

    out, manual_tok = [], {norm(t) for t, _, _, _ in MANUAL}
    for t, dist in sorted(per.items(), key=lambda x: -sum(x[1].values())):
        if t in manual_tok:
            continue
        tot = sum(dist.values())
        if tot < min_n:
            continue
        # ① 6자리가 순도를 넘으면 그걸 쓴다
        agg6 = collections.Counter()
        for c, n in dist.items():
            agg6[c] += n
        code6, n6 = agg6.most_common(1)[0]
        # ② 아니면 13대분류를 **직접** 학습한다.
        #   전에는 KECO 1자리를 학습하고 거기서 13분류를 파생했는데, KECO 1·6·8자리는
        #   13분류로 갈려서(1→02/13, 6→07/08, 8→10/12/13) 파생이 실패했다.
        #   `생산`·`가공`·`기계` 같은 고빈도 토큰이 코드 없는 빈 행으로 남았다.
        agg13 = collections.Counter()
        for c, n in dist.items():
            k = keco13.of(c)[0]
            if k:
                agg13[k] += n
        c13, n13 = agg13.most_common(1)[0] if agg13 else ("", 0)
        if tot >= min_n6 and n6 / tot >= min_purity6:
            k13 = keco13.of(code6)
            out.append({"토큰": t, "직종코드": code6, "직종명": m.name.get(code6, ""),
                        "직종분류코드": k13[0], "직종분류명": k13[1],
                        "출처": "학습", "순도": f"{100*n6/tot:.0f}%", "건수": tot,
                        "근거": f"정답 {tot}건 중 {n6}건이 {code6} {m.name.get(code6,'')}"})
        elif c13 and n13 / tot >= min_purity:
            out.append({"토큰": t, "직종코드": "", "직종명": "",
                        "직종분류코드": c13, "직종분류명": keco13.NAMES[c13],
                        "출처": "학습", "순도": f"{100*n13/tot:.0f}%", "건수": tot,
                        "근거": f"정답 {tot}건 중 {n13}건이 {c13} "
                                f"{keco13.NAMES[c13]} — 세세분류는 흩어진다"})
    for t, code, c13, why in MANUAL:
        out.append({"토큰": norm(t), "직종코드": code,
                    "직종명": m.name.get(code, ""),
                    "직종분류코드": c13, "직종분류명": keco13.NAMES.get(c13, ""),
                    "출처": "수동", "순도": "", "건수": "", "근거": why})
    with OUT.open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=COLS)
        w.writeheader(); w.writerows(out)
    n_auto = sum(1 for r in out if r["출처"] == "학습")
    print(f"{OUT.relative_to(BASE)}  {len(out):,}행 (학습 {n_auto:,} · 수동 {len(out)-n_auto})")
    return out


def load_lexicon():
    """{토큰: (6자리코드, 13분류코드, 근거)}

    셋 다 비면 '이 토큰으로는 추정하지 않는다'. 6자리가 없고 13분류만 있으면
    "직군까지만 특정된다" 는 뜻이다.
    """
    if not OUT.exists():
        return {}
    d = {}
    for r in csv.DictReader(OUT.open(encoding="utf-8-sig")):
        t = norm(r["토큰"])
        if t:
            d[t] = ((r["직종코드"] or "").strip(), (r["직종분류코드"] or "").strip(),
                    f"사전({r['출처']}) 「{r['토큰']}」 — {r['근거']}")
    return d


