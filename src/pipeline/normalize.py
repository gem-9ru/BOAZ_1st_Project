ALWAYS = re.compile(r"상시|채용시|수시|충원|마감시|계속")

def norm_deadline(s, collected="2026-09-07"):
    """ISO 날짜와 상시여부를 함께 돌려준다."""
    s = (s or "").strip()
    if not s:
        return "", ""
    if ALWAYS.search(s):
        return "", "상시"
    m = re.match(r"(\d{4})[-./](\d{1,2})[-./](\d{1,2})", s)
    if m:
        y, mo, d = map(int, m.groups())
        return f"{y:04d}-{mo:02d}-{d:02d}", "기한"
    # epoch(초/밀리초)가 문자열로 들어오는 경우 방어 (링커리어 원본 버그 대비)
    if re.fullmatch(r"\d{10,13}", s):
        import datetime as _dt
        n = int(s)
        n = n // 1000 if n > 10 ** 12 else n
        try:
            return _dt.datetime.fromtimestamp(n).strftime("%Y-%m-%d"), "기한"
        except (OverflowError, OSError, ValueError):
            return "", "기타"
    m = re.match(r"(\d{1,2})[/.\-](\d{1,2})$", s)      # '09/16', '09-15' → 수집연도 기준
    if m:
        mo, d = map(int, m.groups())
        y = int(collected[:4])
        if mo < int(collected[5:7]):                     # 연말→연초 롤오버
            y += 1
        return f"{y:04d}-{mo:02d}-{d:02d}", "기한"
    return "", "기타"

