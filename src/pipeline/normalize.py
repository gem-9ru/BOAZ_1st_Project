# 알바 판정 (사용자 요구: 아르바이트 공고는 데이터셋에서 제외)
# ---------------------------------------------------------------------------
# [1차 패턴의 실패] "알바|파트|시급|단기" 식으로 넓게 잡았더니 1,595건이 걸렸는데
# 대부분 오탐이었다. 원인은 두 가지였다.
#   · '파트' 는 한국 회사에서 조직 단위다 — "검색추천파트", "CS 파트 리더",
#     "AI정보화파트 신입", "SW개발 Platform파트" 는 파트타임과 무관하다.
#   · '단기' 는 "차단기", "단기간" 처럼 다른 단어에 섞여 들어온다.
# → '파트' 단독은 버리고 파트타임/파트타이머/P.T 만 인정, 한글 경계를 붙였다.
#   정밀화 후 1,595건 → 752건이 되고 표본이 전부 실제 알바 공고였다.
ALBA_PAT = re.compile(
    r"(?<![가-힣])(아르바이트|알바)(?![가-힣])"
    r"|파트\s?타임|파트\s?타이머|part[\s-]?time|\bP\.?T\b"
    r"|(?<![가-힣])일용(?:직|근로)?(?![가-힣])"
    r"|초단시간"
    r"|단기\s?(노무원|스탭|스태프|알바|사원모집)"
    r"|(?<![가-힣])시급"
    r"|(?<![가-힣])(일당|주급)(?![가-힣])"
    r"|만원\s*/\s*(일|시간)"
    r"|(?<![가-힣])PRN(?![A-Za-z])", re.I)
REGULAR_PAT = re.compile(r"정규|계약|인턴|full[\s-]?time", re.I)


def norm_etype(etype, title, duty):
    """고용형태 표준화 + 알바 여부 판정.

    알바 판정은 '어디에서 매칭됐는지' 를 본다.
      · 공고제목에 매칭  → 알바 (사이트가 고용형태를 '정규직' 으로 잘못 달아둔 경우가 많다.
                          예: 제목 "파트타이머 모집" / 고용형태 "정규직")
      · 고용형태에만 매칭 → 정규·계약·인턴이 함께 적혀 있으면 여러 형태를 함께 받는
                          공고이므로 남기고, 알바 단독이면 제외한다.
      · 직무(상세설명)에만 매칭 → 스쳐 지나가는 언급이라 남긴다.
        (예: "뉴믹스커피 오프라인 스토어 매니저 모집" 본문에 파트타이머 언급)
    """
    raw = " ".join([etype or "", duty or ""])
    kinds = []
    for pat, name in ETYPE_MAP:
        if pat.search(raw):
            kinds.append(name)
    std = ", ".join(dict.fromkeys(kinds)) if kinds else ""

    if ALBA_PAT.search(title or ""):
        return std, True
    if ALBA_PAT.search(etype or ""):
        return std, not REGULAR_PAT.search(etype or "")
    return std, False

