OVERSEAS = re.compile(r"해외|미국|일본|중국|베트남|싱가포르|영국|독일|캐나다|호주|인도|"
                      r"홍콩|대만|태국|필리핀|인도네시아|말레이시아|USA|Japan|China", re.I)

def norm_region(s):
    """'서울 강남구', '경기 성남시 수정구 금토동', '한국 서울', '해외 미국' → (시도, 시군구)."""
    s = re.sub(r"[>·,]", " ", (s or "")).strip()
    if not s:
        return "", ""
    # 원티드는 '한국 서울' 처럼 국가를 앞에 붙인다. 국가 토큰은 떼어낸다.
    s = re.sub(r"^(대한민국|한국|KR|Korea)\s+", "", s, flags=re.I).strip()
    if OVERSEAS.search(s) and not any(k in s for k in SIDO):
        return "해외", re.sub(r"^해외\s*", "", s)[:20]
    toks = s.split()
    sido = ""
    for i, t in enumerate(toks):
        # '전남광주' 처럼 붙어오는 경우까지 앞 2~6글자로 탐색
        for cut in (6, 5, 4, 3, 2):
            if t[:cut] in SIDO:
                sido = SIDO[t[:cut]]
                rest = (t[cut:] + " " + " ".join(toks[i + 1:])).strip()
                break
        if sido:
            break
    else:
        rest = ""
    if not sido:
        # 구/군만 적힌 경우 역매핑으로 시도를 복원 (중복 이름은 등록돼 있지 않아 안전)
        for tok in toks:
            hit = SGG_TO_SIDO.get(tok.strip())
            if hit:
                return hit, tok.strip()
        return "", s[:20]
    m = re.search(r"([가-힣]+(?:시|군|구))", rest)
    return sido, (m.group(1) if m else "")

