def norm_career(s):
    s = (s or "").strip()
    if not s:
        return "", ""
    if re.search(r"무관|전체|any", s, re.I):
        return "무관", "0"
    if re.search(r"신입", s) and not re.search(r"경력", s):
        return "신입", "0"
    m = re.search(r"(\d+)\s*[~\-–]?\s*(\d+)?\s*년", s)
    if m:
        return "경력", m.group(1)
    if re.search(r"경력", s):
        return "경력", ""
    return "기타", ""

