# 규칙ID -> 이 낱말이 공고 어디에든 있으면 그 규칙은 쓰지 않는다.
#
# 정규식 안에 부정 룩어헤드로 넣어 봤지만 교대(`|`) 우선순위 때문에 첫 분기에만
# 걸렸다. 고용24 정답으로 홀드아웃 검증할 때 이게 드러났다.
#   «요양병원 영양실에 근무하실 조리원»  -> MED-영양 이 발화 (정답 532302 급식 보조원)
#   «병원조리원 조리실장 경력채용»       -> MED-코디 가 발화 (정답 531800 급식 조리사)
# 병원의 `실장`·`영양실`은 조리 직무일 수 있다. 조리어가 있으면 손을 뗀다.
EXCLUDE = {
    "MED-영양": r"조리",
    "MED-코디": r"조리|급식|영양실",
}


def match(title: str, tokens: str, industry: str):
    """(규칙ID, 직종코드, 근거) 또는 None."""
    text = f"{title} {tokens}"
    ind = industry or ""
    for rid, tpat, ipat, code, why in RULES:
        if not re.search(tpat, text, re.I):
            continue
        if ipat and not re.search(ipat, ind):
            continue
        neg = EXCLUDE.get(rid)
        if neg and re.search(neg, text, re.I):
            continue
        return rid, code, why
    return None
